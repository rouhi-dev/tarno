/* ------------------------------- تحلیل نتایج ------------------------------- */

export interface HypothesisOutcome {
  hypothesis: ValidationHypothesis;
  support: number;
  reject: number;
  unclear: number;
  /** کل پاسخ‌های «مشخص» (تأیید + رد) */
  decided: number;
  ratio: number;
  status: 'supported' | 'rejected' | 'inconclusive' | 'no-data';
}

export const MIN_DECIDED_FOR_VERDICT = 5;

/**
 * تحلیل وضعیت فرضیه‌ها بر پایه رکوردهای ثبت‌شده.
 * @param onlyFieldRecorded اگر true باشد، رکوردهای «نمونه قالب» نادیده گرفته می‌شوند.
 */
export const analyzeHypotheses = (
  interviews: FieldInterview[],
  onlyFieldRecorded: boolean,
): HypothesisOutcome[] => {
  const pool = onlyFieldRecorded
    ? interviews.filter((i) => i.provenance === 'field-recorded')
    : interviews;

  return HYPOTHESES.map((hypothesis) => {
    let support = 0;
    let reject = 0;
    let unclear = 0;
    for (const itv of pool) {
      const v = itv.verdicts[hypothesis.id];
      if (v === 'support') support += 1;
      else if (v === 'reject') reject += 1;
      else if (v === 'unclear') unclear += 1;
    }
    const decided = support + reject;
    const ratio = decided > 0 ? support / decided : 0;

    let status: HypothesisOutcome['status'] = 'no-data';
    if (decided + unclear === 0) status = 'no-data';
    else if (decided < MIN_DECIDED_FOR_VERDICT) status = 'inconclusive';
    else status = ratio >= hypothesis.acceptThreshold ? 'supported' : 'rejected';

    return { hypothesis, support, reject, unclear, decided, ratio, status };
  });
};

